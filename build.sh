#!/bin/bash
# =============================================================================
# Mvideo - بناء تلقائي للمشروع
# يضمن تثبيت الاعتماديات قبل البناء لتجنب خطأ "tsc: not found"
# =============================================================================
set -e

echo "========================================"
echo "  Mvideo - بدء عملية البناء التلقائي"
echo "========================================"

# التحقق من وجود node_modules
if [ ! -d "node_modules" ] || [ ! -f "node_modules/.package-lock.json" ]; then
    echo ""
    echo "[1/4] node_modules غير موجود - جاري تثبيت الاعتماديات..."
    npm install
    echo ""
    echo "[✓] تم تثبيت الاعتماديات بنجاح"
else
    echo ""
    echo "[1/4] node_modules موجود - تخطي التثبيت"
fi

# تشغيل الفحوصات النوعية (TypeScript)
echo ""
echo "[2/4] فحص أنواع TypeScript..."
npx tsc -b --noEmit
echo "[✓] فحص الأنواع نجح"

# بناء التطبيق للإنتاج
echo ""
echo "[3/4] بناء التطبيق للإنتاج (Vite)..."
npm run build:web
echo "[✓] البناء نجح"

# تشغيل الاختبارات
echo ""
echo "[4/4] تشغيل الاختبارات..."
npm run test
echo "[✓] جميع الاختبارات نجحت"

echo ""
echo "========================================"
echo "  تم البناء بنجاح! 🎉"
echo "========================================"
echo ""
echo "ملفات البناء موجودة في مجلد: dist/"
echo "للتشغيل في وضع التطوير: npm run dev"
echo "========================================"
